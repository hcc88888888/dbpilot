import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const httpMethods = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

function permissionValues(operation) {
  const value = operation['x-dbpilot-permission'];
  if (value === undefined) {
    return [];
  }
  return Array.isArray(value) ? value : [value];
}

function permissionIdentifier(operationId) {
  const normalized = operationId.replace(/[^A-Za-z0-9]+(.)?/g, (_, next = '') => next.toUpperCase());
  const identifier = normalized.charAt(0).toUpperCase() + normalized.slice(1);
  return `Permission${/^\d/.test(identifier) ? `Operation${identifier}` : identifier}`;
}

function collectPermissions(document) {
  const entries = [];
  const operationIds = new Set();

  for (const [apiPath, pathItem] of Object.entries(document.paths ?? {})) {
    for (const method of httpMethods) {
      const operation = pathItem?.[method];
      if (!operation) {
        continue;
      }

      const operationId = operation.operationId;
      if (typeof operationId !== 'string' || operationId.length === 0) {
        throw new Error(`${method.toUpperCase()} ${apiPath} must define an operationId`);
      }
      if (operationIds.has(operationId)) {
        throw new Error(`duplicate operationId ${operationId}`);
      }
      operationIds.add(operationId);

      const values = permissionValues(operation);
      if (values.length !== 1) {
        throw new Error(`${operationId} must define exactly one x-dbpilot-permission; found ${values.length}`);
      }
      if (typeof values[0] !== 'string' || values[0].length === 0) {
        throw new Error(`${operationId} x-dbpilot-permission must be a non-empty string`);
      }

      entries.push({
        operationId,
        permission: values[0],
        identifier: permissionIdentifier(operationId),
      });
    }
  }

  entries.sort((left, right) => {
    if (left.operationId < right.operationId) return -1;
    if (left.operationId > right.operationId) return 1;
    return 0;
  });

  const identifiers = new Set();
  for (const entry of entries) {
    if (identifiers.has(entry.identifier)) {
      throw new Error(`permission constant name collision for ${entry.operationId}: ${entry.identifier}`);
    }
    identifiers.add(entry.identifier);
  }

  return entries;
}

export function renderPermissionSource(document) {
  const entries = collectPermissions(document);
  const constants = entries
    .map(({ identifier, permission }) => `\t${identifier} = ${JSON.stringify(permission)}`)
    .join('\n');
  const mappings = entries
    .map(({ operationId, identifier }) => `\t${JSON.stringify(operationId)}: ${identifier},`)
    .join('\n');

  return `// Code generated by scripts/contracts/generate-permissions.mjs; DO NOT EDIT.\n\npackage openapi\n\nconst (\n${constants}\n)\n\nvar OperationPermissions = map[string]string{\n${mappings}\n}\n`;
}

async function main() {
  const [bundlePath, outputPath] = process.argv.slice(2);
  if (!bundlePath || !outputPath) {
    throw new Error('usage: node generate-permissions.mjs <bundled-openapi.json> <permissions.gen.go>');
  }

  const document = JSON.parse(await readFile(bundlePath, 'utf8'));
  const source = renderPermissionSource(document);
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, 'utf8');
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : undefined;
if (invokedPath === import.meta.url) {
  await main();
}
